"""Convert Tabler outline SVG icons into Android vector drawables (stroke-based, white, tintable)."""
import re, sys, pathlib, xml.etree.ElementTree as ET

def circle(cx, cy, r):
    return f"M{cx-r},{cy}a{r},{r} 0 1,0 {2*r},0a{r},{r} 0 1,0 {-2*r},0"

def ellipse(cx, cy, rx, ry):
    return f"M{cx-rx},{cy}a{rx},{ry} 0 1,0 {2*rx},0a{rx},{ry} 0 1,0 {-2*rx},0"

def rect(x, y, w, h, rx=0, ry=None):
    ry = rx if ry is None else ry
    if not rx:
        return f"M{x},{y}h{w}v{h}h{-w}z"
    return (f"M{x+rx},{y}h{w-2*rx}a{rx},{ry} 0 0 1 {rx},{ry}v{h-2*ry}a{rx},{ry} 0 0 1 {-rx},{ry}"
            f"h{-(w-2*rx)}a{rx},{ry} 0 0 1 {-rx},{-ry}v{-(h-2*ry)}a{rx},{ry} 0 0 1 {rx},{-ry}z")

def f(e, k, d=0.0):
    return float(e.get(k, d))

def convert(svg_text):
    root = ET.fromstring(svg_text)
    out = []
    for e in root.iter():
        tag = e.tag.split('}')[-1]
        if tag == 'path':
            d = e.get('d')
            if e.get('stroke') == 'none' or d == 'M0 0h24v24H0z':
                continue
        elif tag == 'circle': d = circle(f(e,'cx'), f(e,'cy'), f(e,'r'))
        elif tag == 'ellipse': d = ellipse(f(e,'cx'), f(e,'cy'), f(e,'rx'), f(e,'ry'))
        elif tag == 'rect': d = rect(f(e,'x'), f(e,'y'), f(e,'width'), f(e,'height'), f(e,'rx'), e.get('ry') and f(e,'ry'))
        elif tag == 'line': d = f"M{f(e,'x1')},{f(e,'y1')}L{f(e,'x2')},{f(e,'y2')}"
        elif tag in ('polyline', 'polygon'):
            pts = re.split(r'[\s,]+', e.get('points').strip())
            pairs = [f"{pts[i]},{pts[i+1]}" for i in range(0, len(pts), 2)]
            d = "M" + "L".join(pairs) + ("z" if tag == 'polygon' else "")
        else:
            continue
        out.append(f'    <path android:pathData="{d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="1.9" '
                   f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>')
    return ('<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" '
            'android:viewportWidth="24" android:viewportHeight="24">\n' + "\n".join(out) + "\n</vector>\n")

if __name__ == '__main__':
    src, names_file, res_dir, kt_file = sys.argv[1:5]
    names = pathlib.Path(names_file).read_text().split()
    res = pathlib.Path(res_dir); res.mkdir(parents=True, exist_ok=True)
    entries = []
    for n in names:
        p = pathlib.Path(src) / f"{n}.svg"
        if not p.exists():
            print("missing", n); continue
        rn = "ti_" + n.replace('-', '_')
        (res / f"{rn}.xml").write_text(convert(p.read_text()))
        entries.append((n, rn))
    kt = ["package com.xenoorigin.xelauncher.design", "", "import com.xenoorigin.xelauncher.R", "",
          "/** Generated by tools/tabler2vector.py — Tabler Icons (MIT). */", "object XeIcons {",
          "    val all: Map<String, Int> = mapOf("]
    kt += [f'        "{n}" to R.drawable.{rn},' for n, rn in entries]
    kt += ["    )", "", "    fun res(name: String): Int = all[name] ?: R.drawable.ti_category", "}", ""]
    pathlib.Path(kt_file).write_text("\n".join(kt))
    print(len(entries), "icons")
